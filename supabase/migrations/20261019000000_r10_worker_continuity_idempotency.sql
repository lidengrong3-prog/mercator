-- R10: durable Worker fencing, circuit probes, logical budget idempotency and audit evidence.
-- The v2 RPCs coexist with the original protocol so the database can be deployed
-- before the long-lived Worker image. The scheduler only cuts over after it sees
-- three recent protocol-v2 heartbeats.

BEGIN;

ALTER TABLE public.collection_tasks
  ADD COLUMN IF NOT EXISTS lease_token UUID,
  ADD COLUMN IF NOT EXISTS lease_boot_id TEXT,
  ADD COLUMN IF NOT EXISTS budget_request_id TEXT;

ALTER TABLE public.collection_task_attempts
  ADD COLUMN IF NOT EXISTS lease_token UUID,
  ADD COLUMN IF NOT EXISTS budget_request_id TEXT;

ALTER TABLE public.collection_source_policies
  ADD COLUMN IF NOT EXISTS circuit_probe_task_id UUID,
  ADD COLUMN IF NOT EXISTS circuit_probe_lease_token UUID,
  ADD COLUMN IF NOT EXISTS circuit_half_opened_at TIMESTAMPTZ;

ALTER TABLE public.collection_tasks
  DROP CONSTRAINT IF EXISTS collection_tasks_status_check;
ALTER TABLE public.collection_tasks
  ADD CONSTRAINT collection_tasks_status_check
  CHECK (status IN ('queued', 'leased', 'retry_wait', 'succeeded', 'dead_letter', 'budget_blocked', 'cancelled'));

CREATE TABLE IF NOT EXISTS public.collection_source_outcomes (
  lease_token UUID PRIMARY KEY,
  task_id UUID NOT NULL REFERENCES public.collection_tasks(id) ON DELETE CASCADE,
  source_key TEXT NOT NULL REFERENCES public.data_source_registry(source_key) ON DELETE RESTRICT,
  success BOOLEAN NOT NULL,
  error_code TEXT,
  circuit_state_after TEXT NOT NULL CHECK (circuit_state_after IN ('closed', 'open', 'half_open')),
  consecutive_failures_after INTEGER NOT NULL CHECK (consecutive_failures_after >= 0),
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.collection_worker_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL CHECK (event_type IN (
    'task_claimed', 'lease_expired', 'lease_renew_rejected',
    'attempt_write_rejected', 'completion_rejected', 'failure_rejected',
    'task_completed', 'task_failed', 'budget_blocked',
    'circuit_opened', 'circuit_half_opened', 'circuit_closed'
  )),
  task_id UUID REFERENCES public.collection_tasks(id) ON DELETE CASCADE,
  source_key TEXT REFERENCES public.data_source_registry(source_key) ON DELETE RESTRICT,
  worker_id TEXT,
  boot_id TEXT,
  lease_token UUID,
  idempotency_key TEXT UNIQUE,
  detail JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (jsonb_typeof(detail) = 'object')
);

CREATE INDEX IF NOT EXISTS idx_collection_worker_events_created
  ON public.collection_worker_events(created_at DESC, event_type);
CREATE INDEX IF NOT EXISTS idx_collection_source_outcomes_task
  ON public.collection_source_outcomes(task_id, recorded_at DESC);

-- Once an R10 Worker announces itself, protocol-v1 instances stop taking new
-- work. They may still finish a pre-existing, unfenced lease.
CREATE OR REPLACE FUNCTION public.claim_collection_task(
  p_worker_id TEXT,
  p_lease_seconds INTEGER DEFAULT 900
)
RETURNS SETOF public.collection_tasks
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE lease_seconds INTEGER := GREATEST(30, LEAST(COALESCE(p_lease_seconds, 900), 86400));
BEGIN
  IF NULLIF(TRIM(p_worker_id), '') IS NULL THEN
    RAISE EXCEPTION 'WORKER_ID_REQUIRED' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.collection_worker_instances
     WHERE status IN ('starting', 'ready', 'busy')
       AND last_seen_at >= NOW() - INTERVAL '2 minutes'
       AND metadata->>'protocol_version' = '2'
  ) THEN
    RETURN;
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('collection-task-claim', 0));
  UPDATE public.collection_tasks
     SET status = 'queued', lease_owner = NULL, lease_expires_at = NULL,
         last_heartbeat_at = NULL, run_after = NOW(), updated_at = NOW()
   WHERE status = 'leased' AND lease_token IS NULL
     AND lease_expires_at IS NOT NULL AND lease_expires_at <= NOW();

  RETURN QUERY
  WITH candidate AS (
    SELECT task.id
      FROM public.collection_tasks AS task
      JOIN public.collection_source_policies AS policy USING (source_key)
     WHERE task.status IN ('queued', 'retry_wait')
       AND task.run_after <= NOW()
       AND policy.enabled = TRUE
       AND NOT EXISTS (
         SELECT 1
           FROM unnest(task.depends_on_task_keys) AS dependency_key
           LEFT JOIN public.collection_tasks AS dependency ON dependency.task_key = dependency_key
          WHERE dependency.id IS NULL OR dependency.status <> 'succeeded'
       )
       AND policy.circuit_state = 'closed'
       AND (
         SELECT COUNT(*) FROM public.collection_tasks AS active
          WHERE active.source_key = task.source_key
            AND active.status = 'leased' AND active.lease_expires_at > NOW()
       ) < policy.max_concurrency
     ORDER BY task.priority DESC, task.run_after, task.created_at
     FOR UPDATE OF task SKIP LOCKED
     LIMIT 1
  )
  UPDATE public.collection_tasks AS task
     SET status = 'leased', lease_owner = LEFT(TRIM(p_worker_id), 160),
         lease_expires_at = NOW() + make_interval(secs => lease_seconds),
         last_heartbeat_at = NOW(), last_started_at = NOW(),
         attempt_count = task.attempt_count + 1, updated_at = NOW()
    FROM candidate
   WHERE task.id = candidate.id
  RETURNING task.*;
END;
$$;

